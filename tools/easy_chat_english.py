#!/usr/bin/env python3
"""Keep the EASY CHAT words and moves in English for the trendy phrase.

    python tools/easy_chat_english.py --tree build/upstream

The Feebas calculators ask for Dewford's trendy phrase in English. A
translated build stages its own words, so before it does, this writes the
English ones into src/data/easy_chat/easy_chat_words_english.h (a stub in
English builds, from the Emerald 3DS patch for the trendy phrase), and the
game shows the trendy phrase from them. Run by tools/localize_portuguese.py
before it stages the catalogs; it reads the tree's English texts, so it
does nothing on a tree that is already translated.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

import easy_chat_order

OUT = "src/data/easy_chat/easy_chat_words_english.h"
MOVES = "src/data/text/move_names.h"
SYMBOL = re.compile(r'\bconst u8 (gEasyChatWord_\w+)\[\] = _\("((?:[^"\\]|\\.)*)"\);')


def render(tree: Path) -> str:
    words = []
    for path in sorted((tree / easy_chat_order.DATA).glob("easy_chat_group_*.h")):
        words += SYMBOL.findall(path.read_text(encoding="utf-8"))
    moves = easy_chat_order.table(tree, MOVES, "MOVE")
    if not words or not moves:
        raise SystemExit("easy_chat_english: no EASY CHAT words or moves found in %s" % tree)
    out = ["// Generated by tools/easy_chat_english.py from the English texts:",
           "// the EASY CHAT words and moves for the trendy phrase. Do not edit.",
           "#undef CTR_EASY_CHAT_ENGLISH",
           "#define CTR_EASY_CHAT_ENGLISH 1",
           ""]
    out += ['static const u8 sEn_%s[] = _("%s");' % (symbol[len("gEasyChatWord_"):], text)
            for symbol, text in words]
    out += ['static const u8 sEnMove_%s[] = _("%s");' % (name, text) for name, text in moves.items()]
    out += ["",
            "static const struct { const u8 *word; const u8 *english; } sCtrEnglishWordTable[] =",
            "{"]
    out += ["    {%s, sEn_%s}," % (symbol, symbol[len("gEasyChatWord_"):]) for symbol, _ in words]
    out += ["};", "",
            "static const u8 *const sCtrEnglishMoves[MOVES_COUNT] =",
            "{"]
    out += ["    [MOVE_%s] = sEnMove_%s," % (name, name) for name in moves]
    out += ["};", "",
            "static const u8 *CtrEasyChat_EnglishWord(u8 groupId, u16 index)",
            "{",
            "    const u8 *word;",
            "    u32 i;",
            "",
            "    switch (groupId)",
            "    {",
            "    case EC_GROUP_POKEMON:",
            "    case EC_GROUP_POKEMON_NATIONAL:",
            "        return NULL;",
            "    case EC_GROUP_MOVE_1:",
            "    case EC_GROUP_MOVE_2:",
            "        return index < MOVES_COUNT ? sCtrEnglishMoves[index] : NULL;",
            "    }",
            "    word = gEasyChatGroups[groupId].wordData.words[index].text;",
            "    for (i = 0; i < ARRAY_COUNT(sCtrEnglishWordTable); i++)",
            "    {",
            "        if (sCtrEnglishWordTable[i].word == word)",
            "            return sCtrEnglishWordTable[i].english;",
            "    }",
            "    return NULL;",
            "}",
            ""]
    return "\n".join(out)


def write(tree: Path) -> int:
    """Write the English table; returns how many words and moves it holds."""
    if not (tree / OUT).exists():
        return 0  # no patch for the trendy phrase in this tree
    if (tree / ".emerald3ds-locale").exists():
        return 0  # already translated: the table was written before
    text = render(tree)
    (tree / OUT).write_text(text, encoding="utf-8")
    return text.count("static const u8 sEn")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tree", type=Path, required=True)
    args = parser.parse_args()
    print("easy_chat_english: %d texts" % write(args.tree.resolve()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
